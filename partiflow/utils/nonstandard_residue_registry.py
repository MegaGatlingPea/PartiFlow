from __future__ import annotations

import os
from dataclasses import dataclass


ASSET_DIR = os.path.join(os.path.dirname(__file__), "relax_assets")


@dataclass(frozen=True)
class NonstandardResidueSpec:
    resname: str
    proxy_aa: str
    active_pdb_path: str
    passive_pdb_path: str
    active_template: str
    passive_template: str
    connect_atom: str | None = None
    alignment_atoms: tuple[str, ...] | None = None
    active_custom_residue_names: frozenset[str] = frozenset()
    passive_custom_residue_names: frozenset[str] = frozenset()

    @property
    def pdb_path(self) -> str:
        return self.active_pdb_path

    @property
    def custom_residue_names(self) -> frozenset[str]:
        return self.active_custom_residue_names

    def pdb_path_for_role(self, role: str) -> str:
        return self.active_pdb_path if role == "active" else self.passive_pdb_path

    def template_for_role(self, role: str) -> str:
        return self.active_template if role == "active" else self.passive_template

    def custom_residue_names_for_role(self, role: str) -> frozenset[str]:
        return self.active_custom_residue_names if role == "active" else self.passive_custom_residue_names


