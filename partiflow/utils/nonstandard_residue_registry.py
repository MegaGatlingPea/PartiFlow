UNSUPPORTED_NONSTANDARD_RESIDUES: frozenset[str] = frozenset({"DAR", "HYP", "MSE"})


def normalize_resname(value: object) -> str:
    return str(value).strip().upper()


def get_nonstandard_residue_spec(value: object) -> NonstandardResidueSpec | None:
    return NONSTANDARD_RESIDUE_SPECS.get(normalize_resname(value))


def is_supported_nonstandard_residue(value: object) -> bool:
    return get_nonstandard_residue_spec(value) is not None


def is_relax_supported_nonstandard_residue(value: object) -> bool:
    name = normalize_resname(value)
    return name in NONSTANDARD_RESIDUE_SPECS and name not in UNSUPPORTED_NONSTANDARD_RESIDUES
